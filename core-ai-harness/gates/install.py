#!/usr/bin/env python3
"""
Core AI Harness installer.

Deterministic implementation of the /gate-install command so its mechanical
steps do not depend on ad-hoc agent actions. It:

  1. Copies plugin rules (rules/*.md) into <project>/.claude/rules/
  2. Creates <project>/.claude/gates.toml if it does not exist (--force to overwrite)
  3. Deploys FBR gate JARs from a kit directory (--kit)
  4. Verifies the installation and prints a report

The kit layout matches the FBR agent kit (fbr-agent-gates):

    <kit>/tools/.dist/java-lint.jar    -> gates/lint/.dist/java-lint.jar
    <kit>/tools/.dist/error-prone.jar  -> gates/error-prone/.dist/error-prone.jar

The JARs are deployed into the PLUGIN's gates directory (not the project's)
because that is where gate_runner looks for them (GATES_DIR/<gate>/.dist).

Usage:
    python3 install.py [--project-root DIR] [--profile default|fbr]
                       [--kit DIR] [--force] [--json]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

# Path resolution mirrors hooks/_lib/__init__.py.
PLUGIN_ROOT = Path(__file__).resolve().parent.parent
GATES_DIR = PLUGIN_ROOT / "gates"
RULES_DIR = PLUGIN_ROOT / "rules"

# Gates that need an out-of-band binary kit (not shipped in the repo).
# Maps gate name -> jar file name inside <kit>/tools/.dist/.
KIT_JARS = {
    "lint": "java-lint.jar",
    "error-prone": "error-prone.jar",
}
KIT_DIST = "tools/.dist"

# Path segments skipped while probing for framework imports.
_EXCLUDED_SEGMENTS = {"build", "target", "generated", "test"}


def detect_profile(project_root: Path) -> str:
    """Return "fbr" if the project imports the core-ng framework, else "default".

    The fbr profile's shape rules target core-ng conventions, so `import
    core.framework.*` is a reliable signal. Short-circuits on the first hit.
    """
    for java in project_root.rglob("*.java"):
        if any(seg in _EXCLUDED_SEGMENTS for seg in java.parts):
            continue
        try:
            with open(java, encoding="utf-8", errors="ignore") as f:
                for line in f:
                    if line.startswith("import core.framework."):
                        return "fbr"
        except OSError:
            continue
    return "default"


def rules_markdown() -> list[Path]:
    """Plugin rule documents to install (rules/*.md)."""
    return sorted(RULES_DIR.glob("*.md")) if RULES_DIR.exists() else []


def copy_rules(project_root: Path) -> tuple[int, int]:
    """Copy rules/*.md to <project>/.claude/rules/. Returns (copied, skipped)."""
    target = project_root / ".claude" / "rules"
    target.mkdir(parents=True, exist_ok=True)
    copied = skipped = 0
    for src in rules_markdown():
        dst = target / src.name
        if dst.exists() and dst.read_bytes() == src.read_bytes():
            skipped += 1
            continue
        shutil.copy2(src, dst)
        copied += 1
    return copied, skipped


def render_gates_toml(profile: str, with_kit: bool) -> str:
    """Render the default project override file content."""
    lines = [
        "# Core AI Harness - project overrides (generated by /gate-install)",
        "# Overrides are MERGED with the plugin default gates/config.toml.",
        "",
        "[profile]",
        f'active = "{profile}"',
    ]
    if with_kit:
        lines += [
            "",
            "# FBR gates (JARs deployed from the kit)",
            "[gates.lint]",
            "enabled = true",
            "",
            "[gates.error-prone]",
            "enabled = true",
        ]
    return "\n".join(lines) + "\n"


def write_gates_toml(project_root: Path, profile: str, with_kit: bool, force: bool) -> str:
    """Create .claude/gates.toml. Returns "created" | "kept" | "overwritten"."""
    path = project_root / ".claude" / "gates.toml"
    if path.exists() and not force:
        return "kept"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_gates_toml(profile, with_kit), encoding="utf-8")
    return "overwritten" if force else "created"


def deploy_kit(kit_dir: Path, gates_dir: Path | None = None) -> list[str]:
    """Deploy FBR gate JARs from the kit into the plugin gates. Returns report lines.

    `gates_dir` defaults to the module GATES_DIR, read at call time so tests can
    patch `install.GATES_DIR`. Raises FileNotFoundError if the kit is missing a
    required JAR.
    """
    if gates_dir is None:
        gates_dir = GATES_DIR
    report = []
    for gate, jar in KIT_JARS.items():
        src = kit_dir / KIT_DIST / jar
        if not src.exists():
            raise FileNotFoundError(
                f"Kit is missing {KIT_DIST}/{jar} - is {kit_dir} a valid FBR agent kit?"
            )
        dst = gates_dir / gate / ".dist" / jar
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        report.append(f"  {gate}: {dst} ({dst.stat().st_size:,} bytes)")
    return report


def verify_installation(project_root: Path) -> dict:
    """Collect installation facts for the report."""
    rules_target = project_root / ".claude" / "rules"
    return {
        "python": sys.version.split()[0],
        "ast_grep": shutil.which("ast-grep") or shutil.which("sg") or "NOT FOUND",
        "rules_installed": len(list(rules_target.glob("*.md"))) if rules_target.exists() else 0,
        "gates_toml": (project_root / ".claude" / "gates.toml").exists(),
        "lint_jar": (GATES_DIR / "lint" / ".dist" / "java-lint.jar").exists(),
        "error_prone_jar": (GATES_DIR / "error-prone" / ".dist" / "error-prone.jar").exists(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--project-root", type=Path, default=Path.cwd(),
                        help="Target project root (default: current directory)")
    parser.add_argument("--profile", choices=("default", "fbr"), default=None,
                        help="Profile for .claude/gates.toml (default: auto-detect)")
    parser.add_argument("--kit", type=Path, default=None,
                        help="FBR agent kit directory containing tools/.dist/*.jar")
    parser.add_argument("--force", action="store_true",
                        help="Overwrite an existing .claude/gates.toml")
    parser.add_argument("--json", action="store_true", help="Emit a JSON report")
    args = parser.parse_args(argv)

    project_root = args.project_root.resolve()
    if not project_root.is_dir():
        if args.json:
            print(json.dumps({"ok": False, "error": f"project root does not exist: {project_root}"}))
        else:
            print(f"error: project root does not exist: {project_root}", file=sys.stderr)
        return 1

    # 1. Rules
    copied, skipped = copy_rules(project_root)

    # 2. gates.toml
    profile = args.profile or detect_profile(project_root)
    state = write_gates_toml(project_root, profile, args.kit is not None, args.force)

    # 3. Kit (FBR JARs)
    kit_lines = []
    kit_deployed = False
    kit_error = None
    if args.kit:
        try:
            kit_lines = deploy_kit(args.kit.resolve(), gates_dir=GATES_DIR)
            kit_deployed = True
        except FileNotFoundError as e:
            kit_error = str(e)

    # 4. Verify
    verification = verify_installation(project_root)

    if args.json:
        print(json.dumps({
            "ok": kit_error is None,
            "project_root": str(project_root),
            "profile": profile,
            "rules": {"copied": copied, "skipped": skipped,
                      "total": len(rules_markdown())},
            "gates_toml": state,
            "kit_deployed": kit_deployed,
            "kit_error": kit_error,
            "verification": verification,
        }, indent=2))
    else:
        print(f"[install] target: {project_root}")
        print(f"[1/4] rules: copied {copied}, {skipped} already in sync")
        print(f"[2/4] gates.toml: {state} (profile={profile})")
        if args.kit:
            print(f"[3/4] kit: deployed from {args.kit.resolve()}")
            print("\n".join(kit_lines) if kit_lines else "  (nothing deployed)")
        else:
            print("[3/4] kit: skipped (no --kit); lint/error-prone gates need deployed JARs")
        print("[4/4] verification:")
        for key, value in verification.items():
            print(f"  {key}: {value}")
        if kit_error:
            print(f"error: {kit_error}", file=sys.stderr)
        if profile != "default":
            print(f"note: detected core-ng (FBR) project - profile set to {profile}")
        if args.kit and profile == "default":
            print("note: --kit implies FBR gates; pass --profile fbr if this is an FBR project")

    return 1 if kit_error else 0


if __name__ == "__main__":
    sys.exit(main())
